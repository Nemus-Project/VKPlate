ETA=zeros(Ts,Npsi);                           % eta time vector

eta=zeros(Npsi,1);                            % Modal stress vector at n

etam=zeros(Npsi,1);                           % Modal stress vector at n-1

c0=0.08;                                            %Frequency independant damping term

c1=0.04;                                              % Frequency dependant damping term

xi=Id;                                     % Modal damping matrix

xi=(c1*Om.^(0.75)+c0).*Id ;

%xi(1,1)=5e-4;  

%xi(:,:)=0;

xiv = diag(xi);


%l0=1e3;                                        % Drift control term

Omt2=(4/k^2)*(1 - 2*exp(-xiv*k).*cos(k*sqrt(Om.^2-xiv.^2)) +exp(-2*xiv*k)) ...
            ./(1 + 2*exp(-xiv*k).*cos(k*sqrt(Om.^2-xiv.^2)) +exp(-2*xiv*k));   % Omega Tilde square

Omt2=diag(Omt2); % Diagonal matrix of the modified frequencies


xit=(2/k)*(1-exp(-2*xiv*k))...
         ./(1 + 2*exp(-xiv*k).*cos(k*sqrt(Om.^2-xiv.^2)) +exp(-2*xiv*k)); % xi tilde


xit=diag(xit); % Diagonal matrix of the modified damping

DSM=(0.5*k*xi*Id+Id)^-1;                       % Damping term in the scheme

Dqmsv=0.5*k*xi*Id-Id;                          % Damping term in the Stormer-Verlet scheme

Dqpsv=0.5*k*xi*Id+Id;

%correction ?
DqmsvL=k*xit-Id;

Dq0svL=2*Id-Dw2*k^2;

DqpsvL=Id+0.25*Omt2*k^2+k*xit;

DexpsvL=inv(DqpsvL);
%


Dq0L=(2*Id-0.5*(Omt2*k^2));


DSMloss= inv(0.25*(Omt2*k^2) + 0.5*k*xit*Id  + Id); %Lossy version of the diagonal matrix of sherman morrisson




