qmsv=qm;                                        % Initialisation of the displacement at n-1 Stormer-Verlet

q0sv=qmsv;                                      % Initialisation of the displacement at n Stormer-Verlet

Q(1,:)=q0;

Qsv(1,:)=q0sv;

enerr=1/(rho*Lz);                               % Energy multiplicator (see paper)

for ki = 1:Nmodes
    for ji =1:Nmodes
        for ii =1:Nmodes
            eta(ki)=eta(ki)-((E*Lz)/(2*zetafourth(ki)))*Hv(ii,ji,ki)*(q0(ii)*q0(ji)+2*q0(ii)*a0(ji)); % Initialisation of eta
        end
    end
end


etasv=eta;

etasvm=eta;
etasvp=eta;

ETA(1,:)=eta;

ETASV(1,:)=etasv;

U=enerr*(1/(2*E*Lz))*zetafourth(1:Npsi)'*0.5*(eta.^2+eta.^2);   %to change with actual energy (meaning etan-1)

ep=1e-11;                                       % Potential shift

psim1=sqrt(2*U+ep);                             % Initialisation of psi at n-1/2

PSI0(1)=psim1;        

if shouldtestSAV
%% SAV loop
countsav=1;
nsav=1;
tic
for n = 2 : Ts

    En(n)=0.5*sum(((q0-qm)/k).^2);  %Kinetic energy at timestep n

    %V0(n)=0.5*sum(DV0*q0.*qm);      %Linear potential energy at timestep n, lossess case
    
    V0(n) = 0.5*sum(Omt2*(0.5*(q0+qm)).^2);    % New linear potential for lossy cases

    eta(:)=0;

    for li = 1:Npsi
        for mi =1:Nmodes
            for ni =1:Nmodes
                eta(li)=eta(li)-((E*Lz)/(2*zetafourth(li)))*Hv(li,ni,mi)*(q0(mi)*q0(ni)+2*q0(mi)*a0(ni));         %eta computation 

            end
        end
    end

    ETA(n,:)=eta;
 
    U=enerr*(1/(2*E*Lz))*zetafourth(1:Npsi)'*(eta.^2);        %Nonlinear potential energy computation

    dUdq(:)=0;
    for ji = 1:Nmodes
        for ki =1:Npsi
            for ii =1:Nmodes
                dUdq(ji)=dUdq(ji)-eta(ki)*((q0(ii)+2*a0(ii))*Hv(ki,ii,ji));    %dU/dq computation

            end
        end
    end
    %g=enerr*(1/sqrt(2*U+ep))*dUdq;  %g vector computation at each timestep
    
    dr(n)=psim1-sqrt(2*U+ep);
    
    vel =((q0-qm)/k)+ep; % velocity

    g=enerr*(1/sqrt(2*U+ep))*dUdq-l0*dr(n)*(sign(vel)./sign(vel)'*vel); %g with drift control

    G(n)=g(1);

    %Q(n,:)=q0;


    if countsav==os
        countsav=0;
         Q(nsav,:)=q0;
         nsav=nsav+1;
    end
    countsav=countsav+1;

    % Matrix definitions


    Dqnm2=0.25*(k^2)*g*g'+0.5*xi*Id*k-Id;
   
    Dexp2=DSM-(DSM*0.25*(k^2)*g*g'*DSM)/(1+0.25*k^2*g'*DSM*g);


    DqpL= 0.25*(Omt2*k^2) + 0.5*k*xit*Id + 0.25*(k^2)*g*g' + Id;%n+1 for the exact lossy 
    DqmL=-0.25*(Omt2*k^2) + 0.5*k*xit*Id + 0.25*(k^2)*g*g' - Id;%n-1 for the exact lossy 
    %DexpL=inv(DqpL); 
    DexpL = DSMloss - (DSMloss*0.25*(k^2)*g*g'*DSMloss)/(1+g'*DSMloss*0.25*(k^2)*g);

    
    % Timestepping scheme LES 

    %qs=Dexp2*(D0sv*q0+Dqnm2*qm-g*(k^2)*psim1+k^2*pext(:,n));% +k^2*pext(:,n)); %SAV lossless
    %qs=Dexp2*(Ddiag*q0+Dqnm2*qm-g*(k^2)*psim1);% +k^2*pext(:,n)); %SAV lossless working
    

    qs=DexpL*(Dq0L*q0+DqmL*qm-g*(k^2)*psim1+k^2*pext(:,n)); % SAV exact lossy 
    
    psi0=psim1+0.5*g'*(qs-qm); % Psi time stepping
    %psi0=psim1+0.5*g'*(qs-qm)-k*l0*dr(n-1); % Psi control drift (probably
    %wrong, taken into account in g already


    %dr(n)=psi0-sqrt(2*U+ep);
    dr2(n)=(psi0-sqrt(2*U+ep))/sqrt(2*U+ep);


 

